 SELECT A.REST_ID, A.REST_NAME, A.FOOD_TYPE, A.FAVORITES, A.ADDRESS,
 B.SCORE
 FROM REST_INFO A,
 (
    select REST_ID, ROUND(AVG(REVIEW_SCORE),2) AS SCORE
    from  REST_REVIEW 
    group by REST_ID
)B
where A.REST_ID=B.REST_ID
AND A.ADDRESS LIKE '서울%'
order by B.SCORE DESC, A.FAVORITES DESC